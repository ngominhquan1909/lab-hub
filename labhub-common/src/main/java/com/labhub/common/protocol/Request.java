package com.labhub.common.protocol;

import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.databind.JsonNode;

/**
 * Envelope for every client-to-server message.
 *
 * <p>Wire format: a single JSON object on one UTF-8 line, terminated by {@code \n}.
 * Maximum message size is documented in protocol.md (default 64 KB).
 *
 * <pre>
 * {
 *   "requestId": "e2d9d9c3-...",
 *   "type":      "EQUIPMENT_LIST",
 *   "token":     "session-token-string",   // absent for LOGIN
 *   "payload":   { ... }                   // may be null for requests with no body
 * }
 * </pre>
 */
@JsonInclude(JsonInclude.Include.NON_NULL)
public class Request {

    /** UUID generated by the client; echoed in the response for correlation. */
    private String requestId;

    /** Identifies which handler to invoke on the server. */
    private RequestType type;

    /**
     * Session token obtained after successful LOGIN.
     * Absent (null) only for the LOGIN request itself.
     */
    private String token;

    /**
     * Arbitrary JSON payload; structure depends on {@link #type}.
     * Null for requests that carry no body (e.g., LOGOUT, DASHBOARD_STATS).
     */
    private JsonNode payload;

    // ── Constructors ──────────────────────────────────────────────────────

    /** Required by Jackson. */
    public Request() { }

    /**
     * Convenience constructor for requests without a payload.
     *
     * @param requestId unique correlation ID
     * @param type      request type
     * @param token     session token
     */
    public Request(String requestId, RequestType type, String token) {
        this.requestId = requestId;
        this.type = type;
        this.token = token;
    }

    /**
     * Full constructor.
     *
     * @param requestId unique correlation ID
     * @param type      request type
     * @param token     session token
     * @param payload   typed payload serialized as JSON
     */
    public Request(String requestId, RequestType type, String token, JsonNode payload) {
        this.requestId = requestId;
        this.type = type;
        this.token = token;
        this.payload = payload;
    }

    // ── Getters / setters ──────────────────────────────────────────────────

    /** @return unique correlation ID */
    public String getRequestId() { return requestId; }

    /** @param requestId unique correlation ID */
    public void setRequestId(String requestId) { this.requestId = requestId; }

    /** @return request type */
    public RequestType getType() { return type; }

    /** @param type request type */
    public void setType(RequestType type) { this.type = type; }

    /** @return session token */
    public String getToken() { return token; }

    /** @param token session token */
    public void setToken(String token) { this.token = token; }

    /** @return raw JSON payload node */
    public JsonNode getPayload() { return payload; }

    /** @param payload raw JSON payload node */
    public void setPayload(JsonNode payload) { this.payload = payload; }

    @Override
    public String toString() {
        return "Request{requestId='" + requestId + "', type=" + type + "}";
    }
}
